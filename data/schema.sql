CREATE DATABASE IF NOT EXISTS ace_mtech CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ace_mtech;

CREATE TABLE IF NOT EXISTS admins (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	username VARCHAR(64) NOT NULL UNIQUE,
	password_hash VARCHAR(255) NOT NULL,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS clients (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	name VARCHAR(150) NOT NULL,
	image_path VARCHAR(255) NOT NULL,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS partners (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	name VARCHAR(150) NOT NULL,
	image_path VARCHAR(255) NOT NULL,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS products (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	name VARCHAR(150) NOT NULL,
	description TEXT NULL,
	image_path VARCHAR(255) NOT NULL,
	show_in_services TINYINT(1) NOT NULL DEFAULT 0,
	services_order INT NOT NULL DEFAULT 0,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_gallery (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	title VARCHAR(150) NOT NULL,
	caption TEXT NULL,
	alt_text VARCHAR(255) NULL,
	image_path VARCHAR(255) NOT NULL,
	display_order INT NOT NULL DEFAULT 0,
	is_visible TINYINT(1) NOT NULL DEFAULT 1,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_gallery_posts (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	title VARCHAR(150) NOT NULL,
	caption TEXT NULL,
	cover_image_path VARCHAR(255) NOT NULL,
	display_order INT NOT NULL DEFAULT 0,
	is_visible TINYINT(1) NOT NULL DEFAULT 1,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_gallery_images (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	gallery_post_id INT UNSIGNED NOT NULL,
	image_path VARCHAR(255) NOT NULL,
	alt_text VARCHAR(255) NULL,
	display_order INT NOT NULL DEFAULT 0,
	created_at DATETIME NOT NULL,
	CONSTRAINT fk_product_gallery_images_post FOREIGN KEY (gallery_post_id) REFERENCES product_gallery_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS social_links (
	id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	platform_key VARCHAR(32) NOT NULL UNIQUE,
	url VARCHAR(255) NOT NULL,
	display_order INT NOT NULL DEFAULT 0,
	is_visible TINYINT(1) NOT NULL DEFAULT 1,
	created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
